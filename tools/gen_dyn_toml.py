#!/usr/bin/env python3
"""Append a [dynamic_immediates] table built from sotc_dynamic_sites.json to a PS2Recomp config."""
import json, re, sys
cfg, sites = sys.argv[1], sys.argv[2]
d = json.load(open(sites))
addrs = sorted({int(s['addr'], 16) for s in d['sites'] if s['type'] in ('R_MIPS_HI16', 'R_MIPS_LO16')})
text = open(cfg).read()
text = re.sub(r'\n\[dynamic_immediates\]\n(?:addresses = \[[^\]]*\]\n)?', '\n', text)
lines = ',\n'.join('  ' + ', '.join(f'0x{a:08X}' for a in addrs[i:i + 8]) for i in range(0, len(addrs), 8))
text += f'\n[dynamic_immediates]\n# {len(addrs)} sites patched by the game when data sheets load (generated by gen_dyn_toml.py)\naddresses = [\n{lines}\n]\n'
open(cfg, 'w').write(text)
print(f'{len(addrs)} dynamic immediates -> {cfg}')
